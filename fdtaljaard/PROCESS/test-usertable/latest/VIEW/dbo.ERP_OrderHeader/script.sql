CREATE VIEW [dbo].[ERP_OrderHeader]
AS
SELECT        ORDUNIQ, AUDTDATE, AUDTTIME, AUDTUSER, AUDTORG, OEORDH.ORDNUMBER, CUSTOMER, SHIPTO, SHPNAME, SHPADDR1, SHPADDR2, SHPADDR3, SHPADDR4, SHPCITY, SHPSTATE, SHPZIP, SHPCOUNTRY, SHPPHONE, 
                         SHPCONTACT, PONUMBER, TERMS, REFERENCE, ORDDATE, EXPDATE, SHIPVIA, VIADESC, LOCATION, ONHOLD, [DESC], COMMENT, OVERCREDIT, ORDLINES, NUMLABELS, COMPLETE,DROPSHIP 
						 
FROM            [NYODAT].dbo.OEORDH LEFT JOIN [NYODAT].dbo.vDROPSHIP ON OEORDH.ORDNUMBER = vDROPSHIP.ORDNUMBER
WHERE        (TYPE = 1) AND (EXPDATE > 20231201)  AND COMPLETE < 3 AND RTRIM(CUSTOMER) NOT IN ('AMAZ03','AMAZ05') 
